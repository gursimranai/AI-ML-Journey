#include <iostream>

int main() {

    // Declare variables
    int firstNumber = 25;
    int secondNumber = 15;

    // Calculate the result
    int result = firstNumber + secondNumber;

    // Display the result
    std::cout << "First Number: " << firstNumber << '\n';
    std::cout << "Second Number: " << secondNumber << '\n';
    std::cout << "Result: " << result << '\n';

    return 0;
}