#include <iostream>

int main() {

    int a = 10;
    int b = 20;

    int sum = a + b;
    int difference = b - a;
    int product = a * b;

    std::cout << "A = " << a << '\n';
    std::cout << "B = " << b << '\n';
    std::cout << "Sum = " << sum << '\n';
    std::cout << "Difference = " << difference << '\n';
    std::cout << "Product = " << product << '\n';

    return 0;
}