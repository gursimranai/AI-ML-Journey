#include <stdio.h>

int main(void)
{
    int a = 10;
    int b = 20;

    printf("Relational Operators\n");
    printf("========================\n");

    printf("a == b : %d\n", a == b);
    printf("a != b : %d\n", a != b);
    printf("a > b  : %d\n", a > b);
    printf("a < b  : %d\n", a < b);
    printf("a >= b : %d\n", a >= b);
    printf("a <= b : %d\n", a <= b);

    return 0;
}